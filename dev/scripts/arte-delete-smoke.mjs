// Run with Vite running: node dev/scripts/arte-delete-smoke.mjs
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
try {
  for (const width of [1280, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, hasTouch: true })
    await context.addInitScript(() => localStorage.setItem('cio-auth-session', JSON.stringify({ email: 'local@example.test', loginAt: Date.now(), isOwner: true })))
    const page = await context.newPage()
    page.on('dialog', dialog => dialog.accept())
    await page.goto(`${process.env.STUDIO_TEST_URL || 'http://127.0.0.1:5173'}/arte`)
    const base = page.locator('[data-canvas="editor"]')
    await page.getByLabel('Elementos da arte').getByRole('button', { name: /^Título/ }).click()
    await page.getByRole('combobox', { name: 'Fonte', exact: true }).locator('../..').locator('textarea').focus()
    await base.locator('[data-elemento="titulo"]').tap()
    await page.keyboard.press('Delete')
    assert.equal(await base.locator('[data-elemento="titulo"]').count(), 0)
    await page.keyboard.press('Control+z')
    await base.locator('[data-elemento="titulo"]').waitFor()
    await base.locator('[data-elemento="emoji:0"]').tap()
    await page.keyboard.press('Delete')
    assert.equal(await base.locator('[data-elemento="emoji:0"]').count(), 0)
    await page.keyboard.press('Control+z')
    await base.locator('[data-elemento="emoji:0"]').waitFor()
    await page.getByRole('button', { name: /^Modelos de arte/ }).click()
    await page.getByPlaceholder('Buscar por nome, categoria ou texto').fill('Balão e polaroid com pet')
    await page.locator('[data-modelo="cartao:26-cachorro"]').click()
    await page.getByRole('button', { name: 'Usar neste slide', exact: true }).click()
    const canvas = page.locator('[data-canvas="editor"]')
    const field = page.locator('textarea[data-campo="balao"]')
    await field.fill('Teste para apagar')
    const text = canvas.getByText('Teste para apagar', { exact: true })
    // Editing a field, then touching the art must move keyboard focus to the art.
    await text.tap()
    assert.equal(await canvas.evaluate(el => document.activeElement === el), true)
    await page.keyboard.press('Delete')
    assert.equal(await text.isVisible(), false)
    await page.keyboard.press('Control+z')
    assert.equal(await text.isVisible(), true)
    await text.tap()
    const editing = page.getByTestId('painel-camada').locator('textarea[data-campo="balao"]')
    await editing.focus()
    await editing.press('Home')
    await editing.press('Delete')
    assert.equal(await editing.inputValue(), 'este para apagar')
    assert.equal(await canvas.getByText('este para apagar', { exact: true }).isVisible(), true)
    await canvas.getByText('este para apagar', { exact: true }).tap()
    await page.keyboard.press('Backspace')
    assert.equal(await canvas.getByText('este para apagar', { exact: true }).isVisible(), false)
    await page.getByRole('button', { name: 'Desfazer', exact: true }).click()
    assert.equal(await canvas.getByText('este para apagar', { exact: true }).isVisible(), true)
    // A photo layer can also be selected and removed from a previously focused input.
    await field.focus()
    await canvas.locator('.kc > .ft').tap({ position: { x: 10, y: 10 } })
    await page.keyboard.press('Delete')
    assert.equal(await canvas.locator('.kc > .ft').isVisible(), false)
    await page.keyboard.press('Control+z')
    assert.equal(await canvas.locator('.kc > .ft').isVisible(), true)
    console.log(`${width}px: touch selection, Delete/Backspace, typing protection, photo deletion and undo passed`)
    await context.close()
  }
} finally { await browser.close() }
