// Run with Vite running: node dev/scripts/arte-history-smoke.mjs
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
try {
  for (const width of [1280, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, hasTouch: true })
    await context.addInitScript(() => localStorage.setItem('cio-auth-session', JSON.stringify({ email: 'local@example.test', loginAt: Date.now(), isOwner: true })))
    const page = await context.newPage()
    await page.goto(`${process.env.STUDIO_TEST_URL || 'http://127.0.0.1:5173'}/arte`)
    const undo = page.getByRole('button', { name: 'Desfazer', exact: true })
    const redo = page.getByRole('button', { name: 'Refazer', exact: true })
    const title = page.locator('[data-canvas="editor"] [data-elemento="titulo"]')
    const selectTitle = () => page.getByLabel('Elementos da arte').getByRole('button', { name: /^Título/ }).click()
    const field = () => page.getByRole('combobox', { name: 'Fonte', exact: true }).locator('../..').locator('textarea')
    await title.waitFor()
    assert.equal(await undo.isDisabled(), true)
    const original = await title.textContent()
    await selectTitle()
    await field().fill('')
    await field().pressSequentially('Texto novo')
    await undo.click()
    assert.equal(await title.textContent(), original)
    await redo.click()
    assert.equal(await title.textContent(), 'Texto novo')
    // Normal text undo must not undo the preceding art edit.
    await selectTitle()
    await field().press('End')
    await field().pressSequentially(' abc')
    await field().press('Control+z')
    assert.ok((await field().inputValue()).startsWith('Texto novo'))
    await page.getByRole('button', { name: 'Fechar', exact: true }).click()
    await page.getByLabel('Elementos da arte').getByRole('button', { name: 'Apagar título', exact: true }).click()
    assert.equal(await title.count(), 0)
    await page.locator('body').click({ position: { x: 5, y: 5 } })
    await page.keyboard.press('Control+z')
    await title.waitFor()
    await page.keyboard.press('Control+Shift+z')
    assert.equal(await title.count(), 0)
    await undo.click()
    // One continuous slider gesture must be one undo, not one step per mouse move.
    await selectTitle()
    const size = page.getByRole('slider', { name: /^Tamanho:/ })
    const before = await size.inputValue()
    await size.scrollIntoViewIfNeeded()
    const box = await size.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width * 0.8, box.y + box.height / 2, { steps: 12 })
    await page.mouse.up()
    assert.notEqual(await size.inputValue(), before)
    await undo.click()
    await selectTitle()
    assert.equal(await size.inputValue(), before)
    await page.getByRole('button', { name: 'Fechar', exact: true }).click()
    // Duplicating a slide can be undone and redone with its contents intact.
    await page.getByRole('button', { name: 'Duplicar', exact: true }).click()
    assert.match(await page.getByRole('button', { name: /Baixar todos/ }).innerText(), /\(2\)/)
    await undo.click()
    assert.match(await page.getByRole('button', { name: /Baixar todos/ }).innerText(), /\(1\)/)
    await redo.click()
    assert.match(await page.getByRole('button', { name: /Baixar todos/ }).innerText(), /\(2\)/)
    await page.waitForTimeout(300)
    await page.reload()
    await title.waitFor()
    assert.equal(await undo.isDisabled(), true)
    assert.match(await page.getByRole('button', { name: /Baixar todos/ }).innerText(), /\(2\)/)
    console.log(`${width}px: undo/redo, shortcuts, native text undo, grouped slider, slides and saved restoration passed`)
    await context.close()
  }
} finally { await browser.close() }
